def build_rows():
    parsed = [line.split(maxsplit=1) for line in DATE_ROWS.splitlines()]
    expected_ids = [f"{number:06d}" for number in range(1, 353)]
    actual_ids = [image_id for image_id, _ in parsed]
    if actual_ids != expected_ids:
        raise ValueError("DATE_ROWS must contain exactly the sequential IDs 000001-000352")

    rows = []
    for image_id, label_date in parsed:
        if label_date not in {"NONE", "10-14", "06/03/2027", "08/02/2027", "22.11.26"}:
            date.fromisoformat(label_date)

        error_types = []
        if image_id == "000028":
            error_types.extend(["날짜 없음", "비소비기한 날짜 오인 위험"])
        elif image_id == "000078":
            error_types.append("제조일자만 존재")
        elif image_id == "000232":
            error_types.append("날짜 없음")
        if image_id in MULTIPLE_DATES:
            error_types.append("제조일자·소비기한 동시")
        if image_id in MULTIPLE_PRODUCTS:
            error_types.append("여러 날짜·다른 상품")
        if image_id in TWO_DIGIT_YEAR:
            error_types.append("두 자리 연도")
        if image_id == "000043":
            error_types.append("연도 없음")
        if image_id in UNUSUAL_SEPARATOR:
            error_types.append("다양한 구분자")
        if image_id in LOW_VISIBILITY:
            error_types.append("반사·흐림·저대비")
        if image_id in ROTATED_OR_SKEWED:
            error_types.append("회전·기울어짐")
        if image_id in DOT_MATRIX:
            error_types.append("점자형·잉크젯형 인쇄")
        if image_id in NUMERIC_DISTRACTORS:
            error_types.append("전화번호·바코드 오인 위험")
        if not error_types:
            error_types.append("정상")

        special = set(error_types) != {"정상"}
        difficulty = "hard" if image_id in NEEDS_REVIEW or image_id in NO_CONSUMPTION_DATE else "medium" if special else "easy"
        rows.append(
            {
                "image_id": image_id,
                "정답 날짜": label_date,
                "라벨 상태": "needs_review" if image_id in NEEDS_REVIEW else "manual",
                "난이도": difficulty,
                "오류 유형": "; ".join(dict.fromkeys(error_types)),
                "비고": NOTES.get(image_id, ""),
            }
        )
    return rows


def write_csv(path, rows):
    fieldnames = ["image_id", "정답 날짜", "라벨 상태", "난이도", "오류 유형", "비고"]
    with path.open("w", encoding="utf-8-sig", newline="") as output_file:
        writer = csv.DictWriter(output_file, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def main():
    output_dir = Path(__file__).resolve().parents[1]
    rows = build_rows()
    write_csv(output_dir / "validation_000001_000352.csv", rows)
    write_csv(output_dir / "needs_review_000001_000352.csv", [row for row in rows if row["라벨 상태"] == "needs_review"])


if __name__ == "__main__":
    main()
