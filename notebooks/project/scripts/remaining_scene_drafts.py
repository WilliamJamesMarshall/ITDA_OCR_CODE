def proposals():
    fixed=BATCH/'scene_sheet_index.json'
    if not fixed.exists(): ann.write(fixed,ann.read(BATCH/'missing_sheet_index.json'))
    ids=ann.read(fixed)
    out=[]
    for idx,box in BOXES:
        r=ann.read(ann.record_path(ids[idx]['image_id']))
        cell=idx%4;x=cell%2*650;y=cell//2*820+55
        with Image.open(ann.source_path(r)) as im:
            im.thumbnail((640,755));w,h=im.size
        l,t,rr,b=box
        poly=[[(u-x)*r['width']/w,(v-y)*r['height']/h] for u,v in [(l,t),(rr,t),(rr,b),(l,b)]]
        out.append(dict(image_id=r['image_id'],region_id='visual_scene_date',polygon=poly))
    return out

def preview():
    rows=proposals();font=ImageFont.truetype('C:/Windows/Fonts/malgun.ttf',18)
    for start in range(0,len(rows),8):
        board=Image.new('RGB',(1300,1440),'#eeeeee');d=ImageDraw.Draw(board)
        for j,p in enumerate(rows[start:start+8]):
            r=ann.read(ann.record_path(p['image_id']))
            with Image.open(ann.source_path(r)) as im:
                tile=ann.crop(im,p['polygon'])
                if tile.height>tile.width: tile=tile.rotate(-90,expand=True)
                scale=min(1200/tile.width,140/tile.height)
                tile=tile.resize((max(1,round(tile.width*scale)),max(1,round(tile.height*scale))))
                board.paste(tile,(0,j*180+35))
            d.text((5,j*180+3),f'{start+j}: '+p['image_id'],font=font,fill='black')
        board.save(BATCH/'sheets'/f'scene_{start//8:03d}.jpg',quality=96)
    ann.write(BATCH/'scene_proposals.json',rows)
    print(len(rows))

